#!/usr/bin/env python3
"""Generate the spellchecker's vendored word lists (stdlib only).

Downloads SCOWL 2020.12.07 (http://wordlist.sourceforge.net, the same source the
previous Hunspell dictionaries were generated from) and emits two flat,
fully-expanded word lists with frequency bands:

    parrot-app/assets/dictionaries/en_US.txt
    parrot-app/assets/dictionaries/en_GB.txt

Each line is ``{band} {word}`` (`band` is SCOWL's size level: lower = more common;
the checker ranks suggestions by it). Lines starting with ``#`` are the required
SCOWL copyright/permission notice plus provenance — keep them: the SCOWL license
requires the notice in every copy and in supporting documentation
(see THIRD_PARTY_LICENSES.md).

US composition (mirrors the en_US size-60 dictionary): shared english- words,
american- variants, shared contractions, top-1000 proper names and uppercase
words, bands 10-60. GB is the same with british- variants (the -ise spellings).

Accents are stripped (NFKD + drop combining marks), matching the ``--accents=strip``
build of the previous dictionaries; everything is lowercased; only [a-z'] survives.
Run from the repo root: ``python3 scripts/generate_wordlists.py``.
"""

import unicodedata
import urllib.request
import tarfile
import tempfile
from pathlib import Path

TARBALL_URL = (
    "https://downloads.sourceforge.net/project/wordlist/SCOWL/2020.12.07/"
    "scowl-2020.12.07.tar.gz"
)
BANDS = [10, 20, 35, 40, 50, 55, 60]
CONTRACTION_BANDS = [10, 35, 40, 50, 60]
US_EXTRA = [
    (50, "english-proper-names.50"),
    (50, "american-proper-names.50"),
    (50, "american-upper.50"),
    (60, "american-upper.60"),
]
GB_EXTRA = [(50, "english-proper-names.50")]

COPYRIGHT_HEADER = """\
# English spelling word list for Parrot's checker, generated from SCOWL 2020.12.07
# ({url}).
# Format: one "NN word" per line (NN = SCOWL's size level, which doubles
# as a frequency rank: lower = more common), used to order spelling suggestions.
# Generated by scripts/generate_wordlists.py — do not hand-edit; re-run the script.
#
# Copyright 2000-2018 by Kevin Atkinson
#
# Permission to use, copy, modify, distribute and sell these word
# lists, the associated scripts, the output created from the scripts,
# and its documentation for any purpose is hereby granted without fee,
# provided that the above copyright notice appears in all copies and
# that both that copyright notice and this permission notice appear in
# supporting documentation. Kevin Atkinson makes no representations
# about the suitability of this array for any purpose. It is provided
# "as is" without express or implied warranty.
""".format(url=TARBALL_URL)


def clean(line: str) -> str | None:
    line = line.strip()
    if not line:
        return None
    line = unicodedata.normalize("NFKD", line)
    line = "".join(c for c in line if not unicodedata.combining(c))
    line = line.lower()
    if not line:
        return None
    for c in line:
        if not ((c.isalpha() and c.isascii()) or c == "'"):
            return None
    return line


def build(final_dir: Path, files: list[tuple[int, str]]) -> dict[str, int]:
    words: dict[str, int] = {}
    for band, name in files:
        path = final_dir / name
        if not path.exists():
            print(f"  skip missing {name}")
            continue
        raw = path.read_bytes().decode("latin-1")
        added = 0
        for raw_line in raw.splitlines():
            word = clean(raw_line)
            if word and word not in words:
                words[word] = band
                added += 1
        print(f"  {name}: {added} new words")
    return words


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    out_dir = repo_root / "parrot-app" / "assets" / "dictionaries"
    out_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="scowl-") as tmp:
        tarball = Path(tmp) / "scowl.tar.gz"
        print(f"downloading {TARBALL_URL} ...")
        urllib.request.urlretrieve(TARBALL_URL, tarball)
        print("extracting word lists ...")
        with tarfile.open(tarball) as tf:
            tf.extractall(tmp, filter="data")
        final_dir = Path(tmp) / "scowl-2020.12.07" / "final"

        defs = {
            "en_US.txt": (
                [(b, f"english-words.{b}") for b in BANDS]
                + [(b, f"american-words.{b}") for b in BANDS]
                + [(b, f"english-contractions.{b}") for b in CONTRACTION_BANDS]
                + US_EXTRA
            ),
            "en_GB.txt": (
                [(b, f"english-words.{b}") for b in BANDS]
                + [(b, f"british-words.{b}") for b in BANDS]
                + [(b, f"english-contractions.{b}") for b in CONTRACTION_BANDS]
                + GB_EXTRA
            ),
        }
        for filename, files in defs.items():
            print(f"{filename}:")
            words = build(final_dir, files)
            lines = [COPYRIGHT_HEADER]
            lines.extend(
                f"{band} {word}\n"
                for word, band in sorted(words.items(), key=lambda kv: (kv[1], kv[0]))
            )
            (out_dir / filename).write_text("".join(lines), encoding="utf-8")
            print(f"  -> {out_dir / filename} ({len(words)} words)")


if __name__ == "__main__":
    main()
